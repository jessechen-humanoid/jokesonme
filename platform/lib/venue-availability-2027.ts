/** 漫才 open mic：2026/11/15 起每兩週的週日晚上（Jesse 提供的規則，不在大廳行事曆上）。 */
export function isOpenMicSunday(date: string) {
  const days = Math.round((Date.parse(`${date}T00:00:00Z`) - Date.parse("2026-11-15T00:00:00Z")) / 86400000);
  return days >= 0 && days % 14 === 0;
}

