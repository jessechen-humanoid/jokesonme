export type Summary = { totalIncome: number; totalExpense: number; netProfit: number };
/** 年度總收入／支出／淨利。給 year（YYYY）就只算該台北日曆年；不給就是全歷史（對帳用）。 */
export function yearSummary(allTxs: Tx[], year?: string): Summary {
  const txs = inYear(allTxs, year);
  const totalIncome = txs.filter((t) => t.amount > 0).reduce((s, t) => s + t.amount, 0);
  const totalExpense = txs.filter((t) => t.amount < 0).reduce((s, t) => s + t.amount, 0);
  return { totalIncome, totalExpense, netProfit: totalIncome + totalExpense };
}

export type CommonFund = {
  commonIncome: number; commonExpense: number; commonNetProfit: number;
  fundReserved: number; fundUsed: number; distributableCommonNet: number;
  /** 上年年底的基金餘額（跨年結轉）；不給 year 時為 0 */
  fundCarryIn: number;
  /** 累計到該年年底的基金餘額 = 上年結轉 + 該年提撥 − 該年動用（Jesse 2026-11-07 拍板：基金是一個持續的池子） */
  fundBalance: number;
};
/**
 * 共同基金：只有「排除成員為空」（全員共同）的列才計入共同收支、才提撥 20%。
 * 任何有排除成員的列（專場票房、專場退款…）都不進基金、也不算共同淨利。
 * 提撥金額取整；可分配 = 共同淨利 − 提撥（兩者相加剛好等於共同淨利）。
 * 給 year 時收支、提撥、動用、可分配只算該年；餘額則逐年結轉（每年各自取整後相加），所以每年畫面上的數字加起來就是餘額。
 */
export function commonFund(allTxs: Tx[], year?: string): CommonFund {
  const one = (txs: Tx[]) => {
    // paidByFund 支出不計入共同支出（避免雙扣），只算進「基金已動用」
    const commonIncome = txs.filter((t) => t.amount > 0 && isShared(t) && !t.paidByFund).reduce((s, t) => s + t.amount, 0);
    const commonExpense = txs.filter((t) => t.amount < 0 && isShared(t) && !t.paidByFund).reduce((s, t) => s + t.amount, 0);
    const commonNetProfit = commonIncome + commonExpense;
    const fundReserved = Math.round(commonNetProfit * COMMON_FUND_RATE);
    const fundUsed = txs.filter((t) => t.amount < 0 && t.paidByFund).reduce((s, t) => s + Math.abs(t.amount), 0);
    return { commonIncome, commonExpense, commonNetProfit, fundReserved, fundUsed, distributableCommonNet: commonNetProfit - fundReserved };
  };
  const cur = one(inYear(allTxs, year));
  let fundCarryIn = 0;
  if (year) {
    const earlier = [...new Set(allTxs.map((t) => yearOf(t.date)).filter((y) => y < year))];
    for (const y of earlier) {
      const f = one(inYear(allTxs, y));
      fundCarryIn += f.fundReserved - f.fundUsed;
    }
  }
  return { ...cur, fundCarryIn, fundBalance: fundCarryIn + cur.fundReserved - cur.fundUsed };
}

export type ShowPnl = { name: string; income: number; expense: number; net: number };
export function showPnl(txs: Tx[]): ShowPnl[] {
  const map = new Map<string, { income: number; expense: number }>();
  for (const t of txs) {
    const s = map.get(t.showName) ?? { income: 0, expense: 0 };
    if (t.amount > 0) s.income += t.amount;
    else s.expense += t.amount;
    map.set(t.showName, s);
  }
  return [...map.entries()].map(([name, d]) => ({ name, income: d.income, expense: d.expense, net: d.income + d.expense }));
}

export type MemberRow = {
  name: string; settled: number; unsettledNet: number; advanceTotal: number;
  advanceCleared: number; advanceUnsettled: number; annualNet: number;
};
/**
 * 成員年度報表。8 位成員一視同仁：傑哥也拿完整一份（他只是平時不領、年底一次拿，所以他的「未收款淨利」會累積到年底）。
 * 給 year 時：年度分配淨利只算該台北日曆年的收支；已收款看結算的「分潤年度」（12 月分潤在隔年 1/10 出款仍算前一年）；
 * 代墊總額／已結清則累計到該年年底（代墊是跨年沖銷的）。
 * 每位成員的分配先用精確小數算，最後以最大餘數法取整，所以 8 人加總恰等於 round(可分配共同淨利 + 非共同分配)。
 */
export function memberEarnings(allTxs: Tx[], allSettlements: Ledger[], allReimbursements: Ledger[], year?: string): MemberRow[] {
  const txs = inYear(allTxs, year);
  const settlements = year ? allSettlements.filter((s) => settlementYearOf(s) === year) : allSettlements;
  const upToYearEnd = <T extends { date: string }>(rows: T[]) => (year ? rows.filter((r) => r.date <= `${year}-12-31`) : rows);
  const advanceTxs = upToYearEnd(allTxs);
  const reimbursements = upToYearEnd(allReimbursements);

  const { distributableCommonNet } = commonFund(txs);
  const zero = () => Object.fromEntries(MEMBERS.map((m) => [m, 0])) as Record<string, number>;
  const nonSharedIncome = zero();
  const nonSharedExpense = zero();
  for (const t of txs) {
    if (isShared(t) || t.amount === 0 || t.paidByFund) continue;
    const included = MEMBERS.filter((m) => !t.excludedMembers.includes(m));
    const share = included.length > 0 ? t.amount / included.length : 0;
    const bucket = t.amount > 0 ? nonSharedIncome : nonSharedExpense;
    for (const m of included) bucket[m] += share;
  }
  const settled = zero();
  for (const s of settlements) if (s.member in settled) settled[s.member] += s.amount;
  const advanceTotal = zero();
  for (const t of advanceTxs) if (t.advancedBy && t.advancedBy in advanceTotal) advanceTotal[t.advancedBy] += Math.abs(t.amount);
  const reimbursed = zero();
  for (const r of reimbursements) if (r.member in reimbursed) reimbursed[r.member] += r.amount;

  const commonShare = distributableCommonNet / MEMBERS.length;
  const annual = roundPreservingSum(MEMBERS.map((m) => commonShare + nonSharedIncome[m] + nonSharedExpense[m]));
  return MEMBERS.map((m, i) => {
    const annualNet = annual[i];
    const st = Math.round(settled[m]);
    const advT = Math.round(advanceTotal[m]);
    const advC = Math.round(reimbursed[m]);
    return { name: m, settled: st, unsettledNet: annualNet - st, advanceTotal: advT, advanceCleared: advC, advanceUnsettled: advT - advC, annualNet };
  });
}

/**
 * 以前年度還沒付清的分潤（財務總覽的提示用）：對每個早於 year 的年度，數出「未付 > 0」的成員數與合計。
 * 直接用 memberEarnings 逐年算，所以數字與切到那一年看到的「未付」一致；超付（負數）不算。
 * 只回傳還有人未付的年度，由新到舊。
 */
export type PriorYearUnpaid = { year: string; members: number; amount: number };
export function priorYearsUnpaid(allTxs: Tx[], allSettlements: Ledger[], allReimbursements: Ledger[], years: readonly string[], year: string): PriorYearUnpaid[] {
  const out: PriorYearUnpaid[] = [];
  for (const y of [...new Set(years)].filter((v) => v < year).sort((a, b) => b.localeCompare(a))) {
    const unpaid = memberEarnings(allTxs, allSettlements, allReimbursements, y).filter((m) => m.unsettledNet > 0);
    if (unpaid.length) out.push({ year: y, members: unpaid.length, amount: unpaid.reduce((s, m) => s + m.unsettledNet, 0) });
  }
  return out;
}

/** 代墊結清狀態：各成員還款池 = 代墊還款帳本加總；該成員所有代墊交易依日期、同日依列順序，由舊到新沖銷。 */
export type SettleStatus = { status: "settled" | "partial" | "unsettled"; reimbursedAmount: number };
export function deriveSettleStatus(txs: Tx[], reimbursements: Ledger[]): Map<string, SettleStatus> {
  const result = new Map<string, SettleStatus>();
  const pools: Record<string, number> = {};
  for (const r of reimbursements) pools[r.member] = (pools[r.member] ?? 0) + r.amount;
  const byMember = new Map<string, Tx[]>();
  for (const t of txs) {
    if (!t.advancedBy) continue;
    byMember.set(t.advancedBy, [...(byMember.get(t.advancedBy) ?? []), t]);
  }
  for (const [member, advances] of byMember) {
    advances.sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : a.sortOrder - b.sortOrder));
    let pool = pools[member] ?? 0;
    for (const t of advances) {
      const amt = Math.abs(t.amount);
      if (pool >= amt) {
        result.set(t.id, { status: "settled", reimbursedAmount: amt });
        pool -= amt;
      } else if (pool > 0) {
        result.set(t.id, { status: "partial", reimbursedAmount: pool });
        pool = 0;
      } else {
        result.set(t.id, { status: "unsettled", reimbursedAmount: 0 });
      }
    }
  }
  return result;
}

/** 收入／支出分類佔比（js/analytics.js renderPieChart）：不在固定分類裡的歸到「其他收入／其他支出」，依佔比由高到低。 */
export type CategoryShare = { name: string; amount: number; pct: number };
export function categoryShares(txs: Tx[], type: "income" | "expense"): CategoryShare[] {
  const fixed: readonly string[] = type === "income" ? INCOME_CATEGORIES : EXPENSE_CATEGORIES;
  const fallback = type === "income" ? "其他收入" : "其他支出";
  const items = txs.filter((t) => (type === "income" ? t.amount > 0 : t.amount < 0));
  const total = Math.abs(items.reduce((s, t) => s + t.amount, 0));
  if (total === 0) return [];
  const groups = new Map<string, number>(fixed.map((c) => [c, 0]));
  for (const t of items) {
    const key = groups.has(t.category) ? t.category : fallback;
    groups.set(key, (groups.get(key) ?? 0) + Math.abs(t.amount));
  }
  return fixed
    .map((name) => ({ name, amount: groups.get(name) ?? 0, pct: ((groups.get(name) ?? 0) / total) * 100 }))
    .filter((c) => c.amount > 0)
    .sort((a, b) => b.pct - a.pct);
}

// ---- 財務總覽（2026-11 UI/UX 改版）：每月趨勢、稅務預留、收入組成、依演出 id 的損益、單場分潤預覽 ----

export type MonthRow = { month: number; income: number; expense: number; net: number };
/** 該年 1–12 月的收入／支出（支出為正數方便畫圖）／淨利；沒有資料的月份為 0。 */
export function monthlyTrend(allTxs: Tx[], year: string): MonthRow[] {
  const rows: MonthRow[] = Array.from({ length: 12 }, (_, i) => ({ month: i + 1, income: 0, expense: 0, net: 0 }));
  for (const t of inYear(allTxs, year)) {
    const r = rows[Number(t.date.slice(5, 7)) - 1];
    if (!r) continue;
    if (t.amount > 0) r.income += t.amount;
    else r.expense += -t.amount;
    r.net += t.amount;
  }
  return rows;
}

/** 年度稅務預留：系統自動提列的加總（正數），與提列基礎（收入 − 退款，最低 0；以整年加總顯示）。 */
export function taxReserveSummary(allTxs: Tx[], year: string): { reserved: number; base: number } {
  const txs = inYear(allTxs, year);
  const reserved = txs.filter((t) => t.autoGenerated && t.category === TAX_RESERVE_CATEGORY).reduce((s, t) => s - t.amount, 0);
  const base = Math.max(0, txs.filter((t) => countsTowardTaxBase(t)).reduce((s, t) => s + t.amount, 0));
  return { reserved, base };
}

export const INCOME_GROUPS: ReadonlyArray<{ name: string; categories: readonly string[] }> = [
  { name: "票房", categories: ["演出票房"] },
  { name: "會員", categories: ["付費會員"] },
  { name: "周邊", categories: ["周邊商品"] },
  { name: "贊助", categories: ["品牌贊助", "商演合作"] },
];
export type IncomePart = { name: string; amount: number; pct: number };
/** 收入組成：票房／會員／周邊／贊助／其他（含手續費等分類的正數對帳列，與 yearSummary 的總收入一致）。只回傳金額 > 0 的。 */
export function incomeComposition(txs: Tx[]): IncomePart[] {
  const incomes = txs.filter((t) => t.amount > 0);
  const total = incomes.reduce((s, t) => s + t.amount, 0);
  if (total === 0) return [];
  const parts = INCOME_GROUPS.map((g) => ({ name: g.name, amount: incomes.filter((t) => g.categories.includes(t.category)).reduce((s, t) => s + t.amount, 0) }));
  const known = parts.reduce((s, p) => s + p.amount, 0);
  parts.push({ name: "其他", amount: total - known });
  return parts.filter((p) => p.amount > 0).map((p) => ({ ...p, pct: (p.amount / total) * 100 }));
}

export type ShowPnlRow = { showId: string; name: string; income: number; expense: number; net: number; count: number };
/** 各專案損益，以 show id 分組（名稱另外帶出）；支出為負數。 */
export function showPnlById(txs: ReadonlyArray<Tx & { showId: string }>): ShowPnlRow[] {
  const map = new Map<string, ShowPnlRow>();
  for (const t of txs) {
    const r = map.get(t.showId) ?? { showId: t.showId, name: t.showName, income: 0, expense: 0, net: 0, count: 0 };
    if (t.amount > 0) r.income += t.amount;
    else r.expense += t.amount;
    r.net += t.amount;
    r.count += 1;
    map.set(t.showId, r);
  }
  return [...map.values()];
}

/** 分類小計（演出詳細頁）：依金額由大到小。 */
export function categoryTotals(txs: Tx[]): { category: string; amount: number; count: number }[] {
  const map = new Map<string, { category: string; amount: number; count: number }>();
  for (const t of txs) {
    const r = map.get(t.category) ?? { category: t.category, amount: 0, count: 0 };
    r.amount += t.amount;
    r.count += 1;
    map.set(t.category, r);
  }
  return [...map.values()].sort((a, b) => b.amount - a.amount);
}

/**
 * 單場分潤預覽：這場的每一列分給每位成員多少（與 memberEarnings 同一套規則，但只看這一場、不做年度取整）：
 *   - 全員共同的列先扣 20% 共同基金，剩下 8 人均分；
 *   - 有排除成員的列由參與成員均分（專場、平台手續費永遠 8 人分所以是共同列）；
 *   - 共同基金支付的列不計。
 * 回傳每位成員的小數金額（畫面四捨五入顯示）；8 人加總 = 共同列淨額 × 80% + 非共同列淨額。
 */
export function showSplit(txs: Tx[]): { member: string; amount: number }[] {
  const out = Object.fromEntries(MEMBERS.map((m) => [m, 0])) as Record<string, number>;
  for (const t of txs) {
    if (t.paidByFund || t.amount === 0) continue;
    if (isShared(t)) {
      const share = (t.amount * (1 - COMMON_FUND_RATE)) / MEMBERS.length;
      for (const m of MEMBERS) out[m] += share;
    } else {
      const included = MEMBERS.filter((m) => !t.excludedMembers.includes(m));
      if (!included.length) continue;
      for (const m of included) out[m] += t.amount / included.length;
    }
  }
  return MEMBERS.map((m) => ({ member: m, amount: out[m] }));
}
