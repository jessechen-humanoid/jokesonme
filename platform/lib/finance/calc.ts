export const MEMBERS = ["傑哥", "柏文", "巧達", "芭樂", "又又", "兔子", "大弋", "竹節蟲"] as const;
export const TAX_RESERVE_RATE = 0.03;
export const TAX_RESERVE_CATEGORY = "稅務預留";
export const TAX_RESERVE_NOTE = "系統自動：營所稅預留 3%";
export const FUND_SHOW_NAME = "共同基金支出";
export const COMMON_FUND_RATE = 0.2;
/** 退款：負數支出，會扣減該專案（同分組）的稅務預留基礎；平台手續費不會。 */
export const REFUND_CATEGORY = "退款";
export const INCOME_CATEGORIES = ["演出票房", "付費會員", "商演合作", "周邊商品", "品牌贊助", "其他收入"] as const;
export const EXPENSE_CATEGORIES = ["場地租借", "工作人員", "設備道具", "剪輯製作", "行政雜支", "平台手續", "退款", "稅務預留", "其他支出"] as const;
/** 可手動登記的支出分類：稅務預留只能由系統產生（伺服器與畫面都用這份）。 */
export const MANUAL_EXPENSE_CATEGORIES: readonly string[] = EXPENSE_CATEGORIES.filter((c) => c !== TAX_RESERVE_CATEGORY);

export const isIncomeCategory = (category: string): boolean => (INCOME_CATEGORIES as readonly string[]).includes(category);
export const isExpenseCategory = (category: string): boolean => (EXPENSE_CATEGORIES as readonly string[]).includes(category);

export type Tx = {
  id: string;
  showName: string;
  category: string;
  notes: string;
  amount: number;
  advancedBy: string | null;
  excludedMembers: string[]; // 空陣列 = 全員共同
  date: string; // YYYY-MM-DD
  recordedBy: string | null;
  paidByFund: boolean;
  autoGenerated: boolean;
  sortOrder: number; // 原 Sheet 列順序
};
/** forYear 只有成員結算有：這筆付的是哪一年的分潤（settlements.for_year）；代墊還款與舊 Sheet 資料沒有。 */
export type Ledger = { id: string; member: string; amount: number; date: string; notes: string; sortOrder: number; forYear?: string };

const isShared = (t: Pick<Tx, "excludedMembers">) => t.excludedMembers.length === 0;

// ---- 排除成員：正規化與分組鍵 ----

const memberIndex = (m: string) => {
  const i = (MEMBERS as readonly string[]).indexOf(m);
  return i < 0 ? MEMBERS.length : i;
};
/** 分組用：去重、依成員順序排序（不是成員的名字排最後、依字典序）。不丟錯，舊資料也能分組。 */
export function sortExcluded(list: readonly string[]): string[] {
  return [...new Set(list.map((m) => String(m).trim()).filter(Boolean))].sort((a, b) => memberIndex(a) - memberIndex(b) || a.localeCompare(b));
}
export const groupKey = (list: readonly string[]): string => sortExcluded(list).join(",");

/** 寫入前用：去重、排序，而且每個名字都必須是 8 位成員之一、不能全部排除。不合格就丟錯。 */
export function normalizeExcluded(list: readonly string[]): string[] {
  const sorted = sortExcluded(list);
  const bad = sorted.find((m) => memberIndex(m) >= MEMBERS.length);
  if (bad) throw new Error(`排除成員「${bad}」不是成員`);
  if (sorted.length >= MEMBERS.length) throw new Error("至少要有一位成員分配這筆");
  return sorted;
}

// ---- 年度 ----

/** date 欄位是台北的民用日期（YYYY-MM-DD），所以「台北的日曆年」就是前四碼。 */
export const yearOf = (date: string): string => date.slice(0, 4);
export function inYear<T extends { date: string }>(rows: readonly T[], year: string | undefined): T[] {
  return year ? rows.filter((r) => yearOf(r.date) === year) : [...rows];
}
/**
 * 結算的分潤年度預設規則（Jesse 2026-11-07 拍板）：12 月的分潤在隔年 1/10 出款，所以 1 月出款的歸前一年，其餘歸出款日的年份。
 * 與資料庫 finance_default_settlement_year（0016）一致。
 */
export function defaultSettlementYear(date: string): string {
  const y = Number(yearOf(date));
  return String(date.slice(5, 7) === "01" ? y - 1 : y);
}
/** 這筆結算算哪一年的分潤：有存 forYear 就用它，沒有（舊 Sheet 資料）就套預設規則。 */
export const settlementYearOf = (s: Pick<Ledger, "date" | "forYear">): string => s.forYear ?? defaultSettlementYear(s.date);

/** 年份選單：資料裡出現過的年份（結算看分潤年度）加上今年，由新到舊。 */
export function yearsOf(rows: ReadonlyArray<{ date: string; forYear?: string }>, currentYear: string): string[] {
  return [...new Set([currentYear, ...rows.map((r) => r.forYear ?? yearOf(r.date))])].sort((a, b) => b.localeCompare(a));
}

// ---- 四捨五入 ----

/** 最大餘數法：把一組小數金額湊成整數，總和恰等於 round(Σ)。餘數大的先進位，同餘數依順序（成員順序）。 */
export function roundPreservingSum(values: readonly number[]): number[] {
  const target = Math.round(values.reduce((s, v) => s + v, 0));
  const out = values.map((v) => Math.floor(v));
  let left = target - out.reduce((s, v) => s + v, 0);
  const order = values.map((v, i) => ({ i, frac: v - Math.floor(v) })).sort((a, b) => b.frac - a.frac || a.i - b.i);
  for (const o of order) {
    if (left <= 0) break;
    out[o.i] += 1;
    left--;
  }
  return out;
}

// ---- 稅務預留 ----

/** 自動稅務預留的分組鍵：排除成員＋日期的年度。預留列的日期取自同年度的計入列，所以現有列也用自己的日期對應。 */
export const reserveGroupKey = (excludedMembers: readonly string[], date: string): string => `${groupKey(excludedMembers)}|${yearOf(date)}`;

/**
 * 哪些列算進 3% 的基礎：所有收入（正數），加上退款（「退款」分類、或收入分類的負數列）。
 * 平台手續費等其他支出不扣；系統自動產生的稅務預留本身不算。
 */
export function countsTowardTaxBase(t: Pick<Tx, "amount" | "category" | "autoGenerated">): boolean {
  if (t.autoGenerated && t.category === TAX_RESERVE_CATEGORY) return false;
  if (t.amount > 0) return true;
  return t.amount < 0 && (t.category === REFUND_CATEGORY || isIncomeCategory(t.category));
}

/**
 * 稅務預留：某專案依「排除成員 × 台北日曆年」分組，基礎 = 該組該年的收入 − 退款（最低 0），每組一筆 -round(3%)，
 * 日期取該組該年最新一列（收入或退款）的日期。基礎為 0 的分組不提列。共同基金支出專案不提列。
 * 依年度分開（0019）：某年度的預留只看該年度的列，之後其他年度再進收入或退款都不會改到它；
 * 跨年退款扣在退款當年，當年沒有收入可扣時不產生負的預留，也不回頭改前一年。
 */
export type ReserveGroup = { excludedMembers: string[]; amount: number; date: string };
export function taxReservesForShow(showName: string, showTxs: Tx[]): ReserveGroup[] {
  if (!showName || showName === FUND_SHOW_NAME) return [];
  const groups = new Map<string, { excluded: string[]; total: number; latest: string }>();
  for (const t of showTxs) {
    if (!countsTowardTaxBase(t)) continue;
    const key = reserveGroupKey(t.excludedMembers, t.date);
    const g = groups.get(key) ?? { excluded: sortExcluded(t.excludedMembers), total: 0, latest: t.date };
    g.total += t.amount;
    if (t.date > g.latest) g.latest = t.date;
    groups.set(key, g);
  }
  const out: ReserveGroup[] = [];
  for (const g of groups.values()) {
    const reserve = Math.round(Math.max(g.total, 0) * TAX_RESERVE_RATE);
    if (reserve <= 0) continue;
    out.push({ excludedMembers: g.excluded, amount: -reserve, date: g.latest });
  }
  return out;
}

